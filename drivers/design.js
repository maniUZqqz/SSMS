'use strict';
// Table designer: turns an edited column list into a CREATE TABLE or ALTER TABLE
// script for SQL Server, MySQL / MariaDB, PostgreSQL, SQLite and Oracle.
//
// Column: { name, type, nullable, default, pk, identity, seed, incr, unique, check, collation,
//           description, generated, orig,  uniqueName, checkName, hasDescription, extra, rawDef }
//   orig       the column's original name (absent for new columns)
//   uniqueName / checkName / hasDescription   what exists in the database today (for drops/updates)
//   uniqueIndex   SQL Server: name of a unique index (not a constraint) that makes the column unique
//   extra      SQLite only: column constraints kept verbatim (REFERENCES ...)
//   rawDef     SQLite only: full definition of a generated column, kept verbatim

const { quoteIdent } = require('./common');

// SQLite needs expression defaults in parentheses: DEFAULT (datetime('now')).
function sqliteDefault(v) {
  const s = String(v || '').trim();
  if (!s || s.startsWith('(') || /^(-?\d+(\.\d+)?|'(?:[^']|'')*'|NULL|TRUE|FALSE|CURRENT_(TIME|DATE|TIMESTAMP)|X'[0-9A-F]*')$/i.test(s)) return s;
  return `(${s})`;
}

const qms = s => '[' + String(s).replace(/]/g, ']]') + ']';
const Q = { mssql: qms, ...quoteIdent };
const norm = s => String(s || '').replace(/\s+/g, ' ').trim().toLowerCase();
const str = s => "'" + String(s).replace(/'/g, "''") + "'";
const nstr = s => 'N' + str(s);

function qualified(d, t) {
  const q = Q[d];
  if (d === 'mssql') return `${qms(t.db)}.${qms(t.schema || 'dbo')}.${qms(t.name)}`;
  if (d === 'sqlite') return `${q(t.db || 'main')}.${q(t.name)}`;
  if (d === 'mysql') return `${q(t.db)}.${q(t.name)}`;
  return `${q(t.schema)}.${q(t.name)}`;
}

const SUPPORTS = {
  collation: new Set(['mssql', 'mysql', 'postgres', 'sqlite']),
  description: new Set(['mssql', 'mysql', 'postgres', 'oracle']),
  seed: new Set(['mssql', 'postgres', 'oracle']),
};

function clean(cols) {
  if (!Array.isArray(cols) || !cols.length) throw new Error('A table needs at least one column.');
  const seen = new Set();
  return cols.map(c0 => {
    const t = v => String(v == null ? '' : v).trim();
    const c = {
      name: t(c0.name), type: t(c0.type), nullable: !!c0.nullable, default: t(c0.default), pk: !!c0.pk,
      identity: !!c0.identity, seed: t(c0.seed) || '1', incr: t(c0.incr) || '1', unique: !!c0.unique, check: t(c0.check),
      collation: t(c0.collation), description: t(c0.description), generated: !!c0.generated, orig: c0.orig || null,
      uniqueName: c0.uniqueName || null, uniqueIndex: c0.uniqueIndex || null, checkName: c0.checkName || null, hasDescription: !!c0.hasDescription,
      extra: t(c0.extra), rawDef: c0.rawDef || '',
    };
    if (!c.name) throw new Error('Every column needs a name.');
    if (!c.type && !c.generated) throw new Error(`Column "${c.name}" needs a data type.`);
    if (/;|--|\/\*/.test(c.type + c.collation)) throw new Error(`The data type or collation of "${c.name}" looks invalid.`);
    if (!/^-?\d+$/.test(c.seed) || !/^-?\d+$/.test(c.incr)) throw new Error(`Identity seed and increment of "${c.name}" must be whole numbers.`);
    const k = c.name.toLowerCase();
    if (seen.has(k)) throw new Error(`Duplicate column name "${c.name}".`);
    seen.add(k);
    if (c.pk) c.nullable = false;
    return c;
  });
}

const constraintName = (prefix, t, c) => `${prefix}_${t.name}_${c.name}`.replace(/[^\w]/g, '_');

function colDef(d, c, t, inline) {
  if (d === 'sqlite' && c.rawDef) return c.rawDef;
  const q = Q[d];
  let s = `${q(c.name)} ${c.type}`;
  if (c.collation && SUPPORTS.collation.has(d)) s += d === 'postgres' ? ` COLLATE "${c.collation.replace(/"/g, '')}"` : ` COLLATE ${c.collation}`;
  if (c.identity) {
    if (d === 'mssql') s += ` IDENTITY(${c.seed},${c.incr})`;
    else if (d === 'mysql') s += ' AUTO_INCREMENT';
    else if (d === 'postgres' || d === 'oracle') {
      s += ' GENERATED BY DEFAULT AS IDENTITY' + (c.seed !== '1' || c.incr !== '1' ? ` (START WITH ${c.seed} INCREMENT BY ${c.incr})` : '');
    }
  }
  if (c.default && !c.identity) {
    const v = d === 'sqlite' ? sqliteDefault(c.default) : c.default;
    s += d === 'mssql' && inline ? ` CONSTRAINT ${qms(constraintName('DF', t, c))} DEFAULT ${v}` : ` DEFAULT ${v}`;
  }
  if (!c.nullable) s += ' NOT NULL';
  else if (d === 'mssql' || d === 'mysql') s += ' NULL';
  if (inline && c.unique && !c.pk) s += d === 'mssql' ? ` CONSTRAINT ${qms(constraintName('UQ', t, c))} UNIQUE` : ' UNIQUE';
  if (inline && c.check) {
    if (d === 'mssql') s += ` CONSTRAINT ${qms(constraintName('CK', t, c))} CHECK (${c.check})`;
    else s += `${d === 'sqlite' && c.checkName ? ` CONSTRAINT ${q(c.checkName)}` : ''} CHECK (${c.check})`;
  }
  if (d === 'mysql' && c.description) s += ` COMMENT ${str(c.description)}`;
  if (d === 'sqlite' && c.extra) s += ' ' + c.extra;
  return s;
}

function descriptionSql(d, t, c, before) {
  const had = before ? before.hasDescription : false;
  if (d === 'mssql') {
    const args = `@name = N'MS_Description', @level0type = N'SCHEMA', @level0name = ${nstr(t.schema || 'dbo')}, @level1type = N'TABLE', @level1name = ${nstr(t.name)}, @level2type = N'COLUMN', @level2name = ${nstr(c.name)}`;
    if (!c.description) return had ? `EXEC ${qms(t.db)}.sys.sp_dropextendedproperty ${args};` : '';
    return `EXEC ${qms(t.db)}.sys.${had ? 'sp_updateextendedproperty' : 'sp_addextendedproperty'} ${args}, @value = ${nstr(c.description)};`;
  }
  if (d === 'postgres' || d === 'oracle') {
    if (!c.description && !had) return '';
    return `COMMENT ON COLUMN ${qualified(d, t)}.${Q[d](c.name)} IS ${c.description ? str(c.description) : 'NULL'};`;
  }
  return '';
}

function createTable(d, t, cols) {
  const pk = cols.filter(c => c.pk);
  const inlinePk = d === 'sqlite' && pk.length === 1 && pk[0].identity;
  const lines = cols.map(c => {
    if (inlinePk && c.pk) return `    ${Q[d](c.name)} INTEGER PRIMARY KEY AUTOINCREMENT${c.extra ? ' ' + c.extra : ''}`;
    return '    ' + colDef(d, c, t, true);
  });
  if (pk.length && !inlinePk) {
    lines.push(`    ${d === 'mssql' ? `CONSTRAINT ${qms('PK_' + t.name)} ` : ''}PRIMARY KEY (${pk.map(c => Q[d](c.name)).join(', ')})`);
  }
  return `CREATE TABLE ${qualified(d, t)} (\n${lines.join(',\n')}\n)`;
}

// A column name as it may appear in SQLite SQL: "x", [x], `x` or bare x.
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const idRe = name => new RegExp(`("${esc(name.replace(/"/g, '""'))}"|\\[${esc(name)}\\]|\`${esc(name)}\`|(?<![\\w"\`[])${esc(name)}(?![\\w"\`\\]]))`, 'gi');
// Renames column references, leaving string literals alone.
const dq = s => `"${s.replace(/"/g, '""')}"`;
const renameIdents = (s, renames, quote = dq) => String(s).split(/('(?:[^']|'')*')/).map((part, i) => (i % 2 ? part
  : renames.reduce((acc, [from, to]) => acc.replace(idRe(from), quote(to)), part))).join('');

// SQLite table-level constraints (verbatim) adjusted for renamed / dropped columns.
function adjustConstraints(constraints, renames, dropped) {
  const out = [], removed = [];
  for (const raw of constraints || []) {
    // In FOREIGN KEY (...) REFERENCES t(...) only the first column list belongs to this table.
    const fk = /^((?:CONSTRAINT\s+\S+\s+)?FOREIGN\s+KEY\s*\()([^)]*)(\)[\s\S]*)$/i.exec(raw);
    const head = fk ? fk[2] : raw;
    if (dropped.some(n => idRe(n).test(head))) { removed.push(raw); continue; }
    const renamed = renameIdents(head, renames);
    out.push(fk ? fk[1] + renamed + fk[3] : renamed);
  }
  return { out, removed };
}

// before: columns as loaded; info: { pkName, extras (SQLite index/trigger SQL), constraints (SQLite table constraints) }
function buildScript(d, t, before, after, info = {}, isNew = false) {
  const cols = clean(after);
  if (isNew) {
    if (!t.name) throw new Error('Enter a name for the new table.');
    const create = createTable(d, t, cols);
    const comments = cols.map(c => descriptionSql(d, t, c, null)).filter(Boolean);
    if (d === 'mssql') return `USE ${qms(t.db)}\nGO\n${create};\nGO\n${comments.map(s => s + '\nGO\n').join('')}`;
    return [create + ';', ...comments].join('\n') + '\n';
  }

  const byOrig = new Map(before.map(c => [c.name, c]));
  for (const c of cols) if (c.orig && !byOrig.has(c.orig)) c.orig = null;
  const kept = cols.filter(c => c.orig && !c.generated);
  const added = cols.filter(c => !c.orig && !c.generated);
  const keptNames = new Set(cols.map(c => c.orig).filter(Boolean));
  const dropped = before.filter(b => !keptNames.has(b.name));
  const baseDiff = (b, c) => norm(b.type) !== norm(c.type) || !!b.nullable !== !!c.nullable ||
    String(b.default || '') !== String(c.default || '') || !!b.identity !== !!c.identity || norm(b.collation) !== norm(c.collation);
  const seedDiff = (b, c) => b.identity && c.identity && SUPPORTS.seed.has(d) &&
    (String(b.seed || '1') !== c.seed || String(b.incr || '1') !== c.incr);
  const anyDiff = (b, c) => b.name !== c.name || baseDiff(b, c) || !!b.unique !== !!c.unique || String(b.check || '') !== String(c.check || '') ||
    String(b.description || '') !== String(c.description || '') || seedDiff(b, c);
  const changed = kept.filter(c => anyDiff(byOrig.get(c.orig), c));
  const pkBefore = before.filter(c => c.pk).map(c => c.name);
  const pkAfter = cols.filter(c => c.pk);
  let pkChanged = pkBefore.join('\u0001') !== pkAfter.map(c => c.orig || '\u0000' + c.name).join('\u0001');
  if (d === 'mssql' && changed.some(c => c.pk && baseDiff(byOrig.get(c.orig), c))) pkChanged = true;
  if (!changed.length && !added.length && !dropped.length && !pkChanged) return '';

  const T = qualified(d, t), q = Q[d];
  const L = [];

  if (d === 'mssql') {
    L.push(`USE ${qms(t.db)}`, 'GO', 'SET XACT_ABORT ON;', 'BEGIN TRANSACTION;', 'GO');
    const drop = name => L.push(`ALTER TABLE ${T} DROP CONSTRAINT ${qms(name)};`);
    if (pkChanged && info.pkName) drop(info.pkName);
    const dropIndex = name => L.push(`DROP INDEX ${qms(name)} ON ${T};`);
    for (const b of dropped) {
      for (const n of [b.dfltName, b.uniqueName, b.checkName]) if (n) drop(n);
      if (b.uniqueIndex) dropIndex(b.uniqueIndex);
      L.push(`ALTER TABLE ${T} DROP COLUMN ${qms(b.name)};`);
    }
    for (const c of changed) {
      const b = byOrig.get(c.orig);
      if (!!b.identity !== !!c.identity) throw new Error(`SQL Server cannot add or remove IDENTITY on the existing column "${b.name}". Add a new column instead.`);
      if (seedDiff(b, c)) {
        throw new Error(`SQL Server cannot change the identity seed or increment of the existing column "${b.name}". ` +
          `To restart numbering run: DBCC CHECKIDENT ('${t.schema || 'dbo'}.${t.name}', RESEED, ${c.seed})`);
      }
      const typeOrNull = norm(b.type) !== norm(c.type) || !!b.nullable !== !!c.nullable || norm(b.collation) !== norm(c.collation);
      const dflt = String(b.default || '') !== String(c.default || '');
      const uq = !!b.unique !== !!c.unique || (c.unique && typeOrNull);
      // A column with a CHECK cannot always be renamed (temp tables refuse it), so the check is re-created.
      const renamed = b.name !== c.name;
      const ck = String(b.check || '') !== String(c.check || '') || (c.check && typeOrNull) || (renamed && !!b.checkName);
      if (renamed && c.check) c.check = renameIdents(c.check, [[b.name, c.name]], qms);
      if ((typeOrNull || dflt) && b.dfltName) drop(b.dfltName);
      if (uq && b.uniqueName) drop(b.uniqueName);
      if (uq && b.uniqueIndex) dropIndex(b.uniqueIndex);
      if (ck && b.checkName) drop(b.checkName);
      if (renamed) L.push(`EXEC ${qms(t.db)}.sys.sp_rename ${nstr(`${qms(t.schema || 'dbo')}.${qms(t.name)}.${qms(b.name)}`)}, ${nstr(c.name)}, 'COLUMN';`);
      if (typeOrNull) L.push(`ALTER TABLE ${T} ALTER COLUMN ${qms(c.name)} ${c.type}${c.collation ? ' COLLATE ' + c.collation : ''} ${c.nullable ? 'NULL' : 'NOT NULL'};`);
      if ((typeOrNull || dflt) && c.default) L.push(`ALTER TABLE ${T} ADD CONSTRAINT ${qms(constraintName('DF', t, c))} DEFAULT ${c.default} FOR ${qms(c.name)};`);
      if (uq && c.unique) L.push(`ALTER TABLE ${T} ADD CONSTRAINT ${qms(constraintName('UQ', t, c))} UNIQUE (${qms(c.name)});`);
      if (ck && c.check) L.push(`ALTER TABLE ${T} WITH CHECK ADD CONSTRAINT ${qms(constraintName('CK', t, c))} CHECK (${c.check});`);
      if (String(b.description || '') !== String(c.description || '')) L.push(descriptionSql(d, t, c, b));
    }
    for (const c of added) {
      L.push(`ALTER TABLE ${T} ADD ${colDef(d, c, t, true)};`);
      if (c.description) L.push(descriptionSql(d, t, c, null));
    }
    if (pkChanged && pkAfter.length) L.push(`ALTER TABLE ${T} ADD CONSTRAINT ${qms(info.pkName || 'PK_' + t.name)} PRIMARY KEY (${pkAfter.map(c => qms(c.name)).join(', ')});`);
    L.push('COMMIT TRANSACTION;', 'GO');
    // Each statement in its own batch, so later statements see earlier changes.
    return L.filter(Boolean).map(s => (/^(GO|USE |SET |BEGIN |COMMIT )/.test(s) ? s : s + '\nGO')).join('\n') + '\n';
  }

  if (d === 'mysql') {
    const parts = [];
    if (pkChanged && pkBefore.length) parts.push('DROP PRIMARY KEY');
    for (const b of dropped) parts.push(`DROP COLUMN ${q(b.name)}`);
    for (const c of changed) {
      const b = byOrig.get(c.orig);
      if (!!b.unique !== !!c.unique && b.uniqueName) parts.push(`DROP INDEX ${q(b.uniqueName)}`);
      if (String(b.check || '') !== String(c.check || '') && b.checkName) parts.push(`DROP CHECK ${q(b.checkName)}`);
      if (b.name !== c.name || baseDiff(b, c) || String(b.description || '') !== String(c.description || '')) {
        parts.push(`CHANGE COLUMN ${q(b.name)} ${colDef(d, c, t, false)}`);
      }
      if (!b.unique && c.unique) parts.push(`ADD UNIQUE KEY ${q(constraintName('UQ', t, c))} (${q(c.name)})`);
      if (c.check && String(b.check || '') !== c.check) parts.push(`ADD CONSTRAINT ${q(constraintName('CK', t, c))} CHECK (${c.check})`);
    }
    for (const c of added) parts.push(`ADD COLUMN ${colDef(d, c, t, true)}`);
    if (pkChanged && pkAfter.length) parts.push(`ADD PRIMARY KEY (${pkAfter.map(c => q(c.name)).join(', ')})`);
    return `ALTER TABLE ${T}\n  ${parts.join(',\n  ')};\n`;
  }

  if (d === 'postgres') {
    L.push('BEGIN;');
    if (pkChanged && info.pkName) L.push(`ALTER TABLE ${T} DROP CONSTRAINT ${q(info.pkName)};`);
    for (const b of dropped) L.push(`ALTER TABLE ${T} DROP COLUMN ${q(b.name)};`);
    for (const c of changed) {
      const b = byOrig.get(c.orig);
      if (b.name !== c.name) L.push(`ALTER TABLE ${T} RENAME COLUMN ${q(b.name)} TO ${q(c.name)};`);
      const col = `ALTER TABLE ${T} ALTER COLUMN ${q(c.name)}`;
      if (norm(b.type) !== norm(c.type) || norm(b.collation) !== norm(c.collation)) {
        L.push(`${col} TYPE ${c.type}${c.collation ? ` COLLATE "${c.collation.replace(/"/g, '')}"` : ''} USING ${q(c.name)}::${c.type};`);
      }
      if (!!b.nullable !== !!c.nullable) L.push(`${col} ${c.nullable ? 'DROP' : 'SET'} NOT NULL;`);
      if (String(b.default || '') !== String(c.default || '')) L.push(c.default ? `${col} SET DEFAULT ${c.default};` : `${col} DROP DEFAULT;`);
      if (!b.identity && c.identity) L.push(`${col} ADD GENERATED BY DEFAULT AS IDENTITY${c.seed !== '1' || c.incr !== '1' ? ` (START WITH ${c.seed} INCREMENT BY ${c.incr})` : ''};`);
      if (b.identity && !c.identity) L.push(`${col} DROP IDENTITY IF EXISTS;`);
      if (seedDiff(b, c)) L.push(`${col} SET START WITH ${c.seed} SET INCREMENT BY ${c.incr};`);
      if (!!b.unique !== !!c.unique) {
        if (b.uniqueName) L.push(`ALTER TABLE ${T} DROP CONSTRAINT ${q(b.uniqueName)};`);
        if (c.unique) L.push(`ALTER TABLE ${T} ADD CONSTRAINT ${q(constraintName('uq', t, c))} UNIQUE (${q(c.name)});`);
      }
      if (String(b.check || '') !== String(c.check || '')) {
        if (b.checkName) L.push(`ALTER TABLE ${T} DROP CONSTRAINT ${q(b.checkName)};`);
        if (c.check) L.push(`ALTER TABLE ${T} ADD CONSTRAINT ${q(constraintName('ck', t, c))} CHECK (${c.check});`);
      }
      if (String(b.description || '') !== String(c.description || '')) L.push(descriptionSql(d, t, c, b));
    }
    for (const c of added) {
      L.push(`ALTER TABLE ${T} ADD COLUMN ${colDef(d, c, t, true)};`);
      if (c.description) L.push(descriptionSql(d, t, c, null));
    }
    if (pkChanged && pkAfter.length) L.push(`ALTER TABLE ${T} ADD PRIMARY KEY (${pkAfter.map(c => q(c.name)).join(', ')});`);
    L.push('COMMIT;');
    return L.filter(Boolean).join('\n') + '\n';
  }

  if (d === 'oracle') {
    if (pkChanged && pkBefore.length) L.push(`ALTER TABLE ${T} DROP PRIMARY KEY`);
    for (const b of dropped) L.push(`ALTER TABLE ${T} DROP COLUMN ${q(b.name)}`);
    for (const c of changed) {
      const b = byOrig.get(c.orig);
      if (!!b.identity !== !!c.identity) throw new Error(`Changing IDENTITY on the existing column "${b.name}" is not supported. Add a new column instead.`);
      if (b.name !== c.name) L.push(`ALTER TABLE ${T} RENAME COLUMN ${q(b.name)} TO ${q(c.name)}`);
      const parts = [];
      if (norm(b.type) !== norm(c.type)) parts.push(c.type);
      if (String(b.default || '') !== String(c.default || '')) parts.push(`DEFAULT ${c.default || 'NULL'}`);
      if (!!b.nullable !== !!c.nullable) parts.push(c.nullable ? 'NULL' : 'NOT NULL');
      if (parts.length) L.push(`ALTER TABLE ${T} MODIFY (${q(c.name)} ${parts.join(' ')})`);
      if (seedDiff(b, c)) L.push(`ALTER TABLE ${T} MODIFY (${q(c.name)} GENERATED BY DEFAULT AS IDENTITY (START WITH ${c.seed} INCREMENT BY ${c.incr}))`);
      if (!!b.unique !== !!c.unique) {
        if (b.uniqueName) L.push(`ALTER TABLE ${T} DROP CONSTRAINT ${q(b.uniqueName)}`);
        if (c.unique) L.push(`ALTER TABLE ${T} ADD CONSTRAINT ${q(constraintName('UQ', t, c).toUpperCase().slice(0, 128))} UNIQUE (${q(c.name)})`);
      }
      if (String(b.check || '') !== String(c.check || '')) {
        if (b.checkName) L.push(`ALTER TABLE ${T} DROP CONSTRAINT ${q(b.checkName)}`);
        if (c.check) L.push(`ALTER TABLE ${T} ADD CONSTRAINT ${q(constraintName('CK', t, c).toUpperCase().slice(0, 128))} CHECK (${c.check})`);
      }
      if (String(b.description || '') !== String(c.description || '')) L.push(descriptionSql(d, t, c, b).replace(/;$/, ''));
    }
    for (const c of added) {
      L.push(`ALTER TABLE ${T} ADD (${colDef(d, c, t, true)})`);
      if (c.description) L.push(descriptionSql(d, t, c, null).replace(/;$/, ''));
    }
    if (pkChanged && pkAfter.length) L.push(`ALTER TABLE ${T} ADD PRIMARY KEY (${pkAfter.map(c => q(c.name)).join(', ')})`);
    return L.filter(Boolean).map(s => s + ';').join('\n') + '\n';
  }

  if (d === 'sqlite') {
    const renames = changed.filter(c => byOrig.get(c.orig).name !== c.name).map(c => [byOrig.get(c.orig).name, c.name]);
    const simple = !pkChanged &&
      changed.every(c => { const b = byOrig.get(c.orig); return !anyDiff({ ...b, name: c.name }, c); }) &&
      added.every(c => !c.pk && !c.identity && !c.unique && (c.nullable || c.default)) &&
      dropped.every(b => !b.pk && !b.unique && !b.generated) &&
      !adjustConstraints(info.constraints, [], dropped.map(b => b.name)).removed.length;
    if (simple) {
      for (const [from, to] of renames) L.push(`ALTER TABLE ${T} RENAME COLUMN ${q(from)} TO ${q(to)};`);
      for (const b of dropped) L.push(`ALTER TABLE ${T} DROP COLUMN ${q(b.name)};`);
      for (const c of added) L.push(`ALTER TABLE ${T} ADD COLUMN ${colDef(d, c, t, true)};`);
      return L.join('\n') + '\n';
    }
    // SQLite cannot change types, NOT NULL, defaults or keys in place: rebuild the table and copy the data.
    // Column constraints (CHECK, UNIQUE, COLLATE, REFERENCES) and table constraints are carried over.
    // Renames run first as real RENAME COLUMNs, so SQLite also updates views and triggers that use the column;
    // the SQL captured before (constraints, indexes, generated columns) is renamed here to match.
    const tmp = { db: t.db, name: `${t.name}__new` };
    const droppedNames = dropped.map(b => b.name);
    const { out: tableConstraints, removed } = adjustConstraints(info.constraints, renames, droppedNames);
    for (const c of cols) {
      if (c.check) c.check = renameIdents(c.check, renames);
      if (c.rawDef) c.rawDef = renameIdents(c.rawDef, renames);
    }
    let create = createTable(d, tmp, cols);
    if (tableConstraints.length) create = create.replace(/\n\)$/, `,\n${tableConstraints.map(s => '    ' + s).join(',\n')}\n)`);
    const extras = [];
    for (const raw of info.extras || []) {
      const s = String(raw).trim();
      const isIndex = /^CREATE\s+(UNIQUE\s+)?INDEX/i.test(s);
      // An index is re-created only if all its columns still exist (the part after ON table names them).
      const cut = isIndex ? s.search(/\(/) : 0;
      if (isIndex && droppedNames.some(n => idRe(n).test(s.slice(cut)))) { removed.push(s); continue; }
      extras.push((isIndex ? s.slice(0, cut) + renameIdents(s.slice(cut), renames) : renameIdents(s, renames)).replace(/;?$/, ';'));
    }
    for (const r of removed) L.push(`-- Removed because it uses a dropped column: ${r.replace(/\s+/g, ' ')}`);
    L.push('PRAGMA foreign_keys = OFF;', 'BEGIN;');
    for (const [from, to] of renames) L.push(`ALTER TABLE ${T} RENAME COLUMN ${q(from)} TO ${q(to)};`);
    L.push('PRAGMA legacy_alter_table = ON;');
    L.push(create + ';');
    const copy = kept.filter(c => !c.generated);
    if (copy.length) L.push(`INSERT INTO ${qualified(d, tmp)} (${copy.map(c => q(c.name)).join(', ')})\n  SELECT ${copy.map(c => q(c.name)).join(', ')} FROM ${T};`);
    L.push(`DROP TABLE ${T};`);
    L.push(`ALTER TABLE ${qualified(d, tmp)} RENAME TO ${q(t.name)};`);
    L.push(...extras);
    L.push('COMMIT;', 'PRAGMA legacy_alter_table = OFF;', 'PRAGMA foreign_keys = ON;');
    return L.join('\n') + '\n';
  }

  throw new Error(`The table designer does not support ${d}.`);
}

